import { error } from '@sveltejs/kit';
import type { RequestHandler } from './$types';
import { sanitizeFileName } from '$lib/server/extract';

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;

export const GET: RequestHandler = async ({ params, locals }) => {
	if (!locals.user) throw error(401, 'Sign in to download study material.');
	if (!UUID.test(params.id)) throw error(404, 'Study material not found.');

	const { data, error: fetchError } = await locals.supabase
		.from('ai_generations')
		.select('title, content, created_at')
		.eq('id', params.id)
		.eq('user_id', locals.user.id)
		.maybeSingle();

	if (fetchError || !data) throw error(404, 'Study material not found.');

	const header = [
		data.title,
		'',
		`Generated by Pinboard on ${new Date(data.created_at).toLocaleDateString('en')}`,
		'AI Generated study aid. Built from community notes and may omit details.',
		'',
		'---',
		''
	].join('\n');

	return new Response(header + data.content, {
		headers: {
			'content-type': 'text/markdown; charset=utf-8',
			'content-disposition': `attachment; filename="${sanitizeFileName(data.title)}.md"`,
			'cache-control': 'no-store'
		}
	});
};
